# -*- coding: utf-8 -*-
"""
配置层 —— 集中管理所有"环境相关的可变值"

【为什么要有这一层】
测试代码里最忌讳出现"魔法值"：URL、账号、超时时间直接写死在用例里。
一旦要切环境（本地 → 测试环境 → 预发），就得全局搜索替换，极易漏改，
而且改完还没法确认改全了。

所以把所有环境相关的值收敛到这一个文件，用例层只引用、不写死。
切换环境改这里一处即可；CI 上还可以用环境变量覆盖（见下面 ENV 处理）。

【分层原则】
    config.py        ← 配置层：环境、账号、超时（本文件）
    utils/           ← 工具层：HTTP 封装、日志
    data/            ← 数据层：测试数据（YAML）
    testcases/       ← 用例层：只写业务逻辑与断言
每一层只依赖它下面的层，不能反向依赖。这样改配置不会波及用例，改用例不会误伤工具。
"""

import os

# ============================================================
# 一、被测服务地址
# ============================================================
# 【设计说明】优先读环境变量，读不到才用默认值。
# 这样 CI 上可以 `set MALL_ADMIN_BASE=http://test-server:8080` 直接切环境，
# 不用改代码 —— 这是"配置与代码分离"的落地方式。
ADMIN_BASE_URL = os.getenv("MALL_ADMIN_BASE", "http://localhost:8080")
PORTAL_BASE_URL = os.getenv("MALL_PORTAL_BASE", "http://localhost:8085")


# ============================================================
# 二、测试账号
# ============================================================
# 【说明】经实测，ums_admin 表中 8 个账号里只有 admin / macro
# 能用默认口令 macro123 登录，其余账号口令已被改过。
ADMIN_USERNAME = os.getenv("MALL_ADMIN_USER", "admin")
ADMIN_PASSWORD = os.getenv("MALL_ADMIN_PASS", "macro123")


# ============================================================
# 三、HTTP 参数
# ============================================================
# 超时设置：不设超时是接口测试的大忌 —— 服务端卡死会让整个测试套件挂起。
# 这里区分「连接超时」和「读取超时」，因为两者的故障含义不同：
#   连接超时 = 服务没起来 / 网络不通
#   读取超时 = 服务起来了但处理太慢
HTTP_TIMEOUT = (5, 15)          # (连接超时秒, 读取超时秒)

# 响应时间断言阈值（毫秒）
# 【为什么要断言响应时间】功能测试也要关注性能基线。
# 一个接口功能正确但慢到 3 秒，上线后就是故障。设个宽松阈值兜底。
RESPONSE_TIME_LIMIT_MS = 3000


# ============================================================
# 四、业务响应码约定 —— 本项目的核心特性
# ============================================================
"""
【非常重要】mall 使用统一响应体 CommonResult，且所有业务响应的
HTTP 状态码一律是 200，真正的结果在响应体的 code 字段里：

    {"code": 200, "message": "操作成功", "data": {...}}
    {"code": 500, "message": "密码不正确", "data": null}

这意味着：**断言绝对不能只看 HTTP 状态码**。
如果只断言 resp.status_code == 200，那么"密码错误""参数非法"这些
失败场景也会被判为通过，接口测试就完全失效了。

所以下面定义业务码常量，所有断言都针对 body 里的 code。
"""
CODE_SUCCESS = 200          # 操作成功
CODE_VALIDATE_FAILED = 404  # 参数校验失败（@Validated 校验不通过）
CODE_FAILED = 500           # 业务异常（Asserts.fail 抛出，如密码错误）
CODE_UNAUTHORIZED = 401     # 未登录 / token 失效
CODE_FORBIDDEN = 403        # 无权限（动态权限校验不通过）


# ============================================================
# 五、请求头
# ============================================================
JSON_HEADERS = {"Content-Type": "application/json;charset=UTF-8"}


def auth_headers(token: str) -> dict:
    """
    构造带 JWT 的请求头。

    【注意 tokenHead 的尾随空格】
    登录接口返回的 tokenHead 是 "Bearer "（末尾有一个空格），
    拼接时必须保留，否则服务端解析 Authorization 头会失败。
    这是接口测试里很容易踩的坑。
    """
    return {"Authorization": f"Bearer {token}"}
